// Regenerates src/components/pando/pandoShapes.ts from public/brand/pando.svg.
// Run with: node scripts/generate-pando-shapes.mjs
//
// The Figma export keeps Pando as 20 separate paths, in this order. We name each one by role so the
// component can animate the pupil and the beanie highlights. The black outline is a single merged
// path (beanie, arm, fingers, legs), so those parts cannot move on their own until the team delivers
// the layered file. If that file changes the order or the count, update ROLES below.
import { readFileSync, writeFileSync } from 'node:fs'

const ROLES = [
  { id: 'outline', fill: 'tinta' },
  { id: 'arm', fill: 'naranja' },
  { id: 'fingerA', fill: 'naranja' },
  { id: 'fingerB', fill: 'naranja' },
  ...Array.from({ length: 12 }, (_, i) => ({ id: `beanieLine${i + 1}`, fill: 'white' })),
  { id: 'body', fill: 'naranja' },
  { id: 'eyeRing', fill: 'tinta' },
  { id: 'eyeWhite', fill: 'white' },
  { id: 'pupil', fill: 'tinta' },
]

const svg = readFileSync(new URL('../public/brand/pando.svg', import.meta.url), 'utf8')
const viewBox = svg.match(/viewBox="([^"]+)"/)[1]
const paths = [...svg.matchAll(/<path\b[^>]*?\sd="([^"]+)"/g)].map((m) => m[1])

if (paths.length !== ROLES.length) {
  throw new Error(`Expected ${ROLES.length} paths, found ${paths.length}. Update ROLES.`)
}

const shapes = ROLES.map((role, i) => ({ ...role, d: paths[i] }))
const out = `// GENERATED by scripts/generate-pando-shapes.mjs from public/brand/pando.svg. Do not edit by hand.
export const pandoViewBox = '${viewBox}'

export type PandoShape = {
  id: string
  fill: 'tinta' | 'naranja' | 'white'
  d: string
}

export const pandoShapes: PandoShape[] = ${JSON.stringify(shapes, null, 2)}
`
writeFileSync(new URL('../src/components/pando/pandoShapes.ts', import.meta.url), out)
console.log(`Wrote ${shapes.length} shapes, viewBox ${viewBox}`)
